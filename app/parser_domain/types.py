"""Центральные доменные типы для контрактов между слоями парсера.

Роль и ответственность:
    - определяет единый набор `Enum` и `dataclass` для обмена данными между UI,
      use-case, доменными парсерами и инфраструктурой;
    - устраняет неявные словари, кортежи и строковые режимы,
      предоставляя явные и переиспользуемые модели.

Границы:
    - не содержит бизнес-алгоритмов, сетевых вызовов, парсинга HTML и сериализации;
    - не управляет состоянием UI и не выполняет преобразования данных во время исполнения.

Взаимодействие с другими ролями:
    - используется слоем сценариев (`application/use_cases`) как входные команды и
      выходные результаты;
    - используется доменными/инфраструктурными парсерами как контракт структуры
      карточек, страниц и статистики.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Mapping

import pandas as pd
from bs4 import BeautifulSoup


class ParserMode(str, Enum):
    """Явный режим парсинга карточек каталога.

    Роль и ответственность:
        - задаёт допустимые режимы парсинга как перечисление вместо строковых литералов.

    Границы:
        - не валидирует внешние параметры и не выполняет выбор алгоритма парсинга.

    Взаимодействие с другими ролями:
        - передаётся в use-case и парсеры категорий как параметр конфигурации сценария.
    """

    BASIC = "basic"
    FULLTABLE = "fulltable"


@dataclass(slots=True, frozen=True)
class ParseProductsCommand:
    """Команда запуска парсинга товаров одной категории.

    Роль и ответственность:
        - инкапсулирует входные параметры сценария парсинга одной ссылки категории.

    Границы:
        - не содержит callback-и выполнения и не хранит промежуточные результаты.

    Взаимодействие с другими ролями:
        - создаётся UI-слоем и передаётся в use-case парсинга товаров.
    """

    category_url: str
    output_filename: str


@dataclass(slots=True, frozen=True)
class ParseCategoryListCommand:
    """Команда пакетного парсинга списка категорий.

    Роль и ответственность:
        - переносит набор ссылок, имя выходного файла и режим парсинга как единый контракт.

    Границы:
        - не хранит статистику выполнения и не описывает поведение ошибок.

    Взаимодействие с другими ролями:
        - создаётся UI-слоем и передаётся в use-case пакетного парсинга.
    """

    links: tuple[str, ...]
    output_filename: str
    parser_mode: ParserMode = ParserMode.BASIC


@dataclass(slots=True, frozen=True)
class CategoryPageRef:
    """Ссылка на страницу категории в рамках пагинации.

    Роль и ответственность:
        - заменяет неявный кортеж `(index, url, soup)` явной моделью страницы.

    Границы:
        - не реализует переходы пагинации и не загружает HTML самостоятельно.

    Взаимодействие с другими ролями:
        - создаётся пагинатором/парсером и используется экстракторами карточек.
    """

    page_index: int
    page_url: str
    soup: BeautifulSoup


@dataclass(slots=True, frozen=True)
class ProductCardBase:
    """Базовая карточка товара из листинга категории.

    Роль и ответственность:
        - задаёт минимальный общий контракт полей для card extractor-ов.

    Границы:
        - не содержит динамические характеристики и не заменяет модель деталей товара.

    Взаимодействие с другими ролями:
        - заполняется инфраструктурными экстракторами карточек и агрегируется
          парсером списка категорий.
    """

    name: str
    brand: str
    price: str
    product_url: str


@dataclass(slots=True, frozen=True)
class ProductCardFull(ProductCardBase):
    """Расширенная карточка товара из листинга.

    Роль и ответственность:
        - расширяет базовый контракт карточки динамическими характеристиками `features`.

    Границы:
        - не включает полную продуктовую страницу и не описывает ошибки извлечения.

    Взаимодействие с другими ролями:
        - используется экстракторами полного режима и слоями агрегации результатов.
    """

    features: Mapping[str, str] = field(default_factory=dict)


@dataclass(slots=True, frozen=True)
class ProductDetails:
    """Полная информация о товаре со страницы товара.

    Роль и ответственность:
        - представляет отдельную модель данных страницы товара, не смешанную с листингом.

    Границы:
        - не заменяет карточку списка категорий и не содержит данных о прогрессе сценария.

    Взаимодействие с другими ролями:
        - заполняется экстрактором деталей товара и возвращается доменным фасадом парсинга.
    """

    title: str
    article: str
    brand: str
    price: str
    availability: str
    description: str
    features: Mapping[str, str] = field(default_factory=dict)


@dataclass(slots=True, frozen=True)
class CategoryParseStats:
    """Статистика выполнения парсинга категории или списка категорий.

    Роль и ответственность:
        - задаёт типизированный контракт итоговой статистики вместо `dict`.

    Границы:
        - не хранит табличные данные товаров и не содержит бинарное содержимое отчётов.

    Взаимодействие с другими ролями:
        - формируется use-case/парсером и отображается в UI либо логировании.
    """

    total_categories: int
    success_categories: int
    failed_categories: int
    failed_links: tuple[str, ...] = ()
    total_products: int = 0
    parser_mode: ParserMode = ParserMode.BASIC


@dataclass(slots=True, frozen=True)
class ProductsParseResult:
    """Результат сценария парсинга товаров одной категории.

    Роль и ответственность:
        - объединяет DataFrame и имя выходного файла в единый выходной контракт.

    Границы:
        - не хранит агрегированную статистику пакетного сценария.

    Взаимодействие с другими ролями:
        - возвращается use-case парсинга товаров в UI/инфраструктурный слой экспорта.
    """

    dataframe: pd.DataFrame
    output_filename: str


@dataclass(slots=True, frozen=True)
class CategoryListParseResult:
    """Результат сценария пакетного парсинга списка категорий.

    Роль и ответственность:
        - инкапсулирует статистику, бинарные данные Excel и имя выходного файла.

    Границы:
        - не содержит промежуточные структуры по отдельным страницам.

    Взаимодействие с другими ролями:
        - возвращается use-case пакетного парсинга в UI для скачивания и отображения отчёта.
    """

    stats: CategoryParseStats
    excel_bytes: bytes
    output_filename: str


@dataclass(slots=True, frozen=True)
class ItemErrorInfo:
    """Описание ошибки обработки одного элемента.

    Роль и ответственность:
        - унифицирует информацию об ошибке элемента для логирования и UI.

    Границы:
        - не хранит traceback-объекты и не управляет политикой повторов.

    Взаимодействие с другими ролями:
        - формируется use-case при обработке исключений и передаётся в callback-и/логи.
    """

    item_index: int
    item_ref: str
    error_type: str
    message: str


@dataclass(slots=True, frozen=True)
class ProgressUpdate:
    """Унифицированное сообщение обновления прогресса.

    Роль и ответственность:
        - задаёт единый контракт для передачи прогресса через callback-и.

    Границы:
        - не хранит бизнес-результаты и не инициирует выполнение операций.

    Взаимодействие с другими ролями:
        - создаётся use-case/парсером и потребляется UI-слоем при отображении статуса.
    """

    percent: float
    message: str
    current: int = 0
    total: int = 0
