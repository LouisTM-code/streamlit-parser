"""Типизированный контекст трассировки для сообщений журналирования.

Роль и ответственность:
    - хранит минимальный набор атрибутов операции парсинга в одном DTO;
    - предоставляет детерминированное представление контекста для добавления в лог.

Границы:
    - не настраивает logging и не отправляет сообщения в обработчики;
    - не содержит бизнес-правил парсинга и UI-логики.

Взаимодействие с другими ролями:
    - используется `TracingLogger` как источник типизированных полей контекста;
    - может заполняться инфраструктурными парсерами при формировании событий лога.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(slots=True, frozen=True)
class TraceContext:
    """DTO контекста трассировки для логирования.

    Роль и ответственность:
        - типизирует метаданные операции в компактной структуре;
        - поддерживает частичное заполнение полей без требования полного контекста.

    Границы:
        - не форматирует итоговую строку лога и не хранит состояние процесса;
        - не выполняет валидацию URL и индексов страниц.

    Взаимодействие с другими ролями:
        - передаётся в `TracingLogger` для обогащения текстового сообщения.
    """

    operation: str | None = None
    url: str | None = None
    page: int | None = None
    item_index: int | None = None
    parser_mode: str | None = None
