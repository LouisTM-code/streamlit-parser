"""Типизированный контекст трассировки для сообщений логирования.

Роль и ответственность:
    - переносит минимальный набор полей, полезных для корреляции логов;
    - обеспечивает единый тип данных для logging-wrapper слоя.

Границы:
    - не форматирует лог-сообщения;
    - не управляет конфигурацией Python logging.

Взаимодействие с другими ролями:
    - передаётся в `TracingLogger` как дополнительный контекст записи;
    - создаётся вызывающими слоями парсинга по мере необходимости.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class TraceContext:
    """DTO контекста трассировки для одной записи лога.

    Роль и ответственность:
        - хранит опциональные атрибуты текущей операции парсинга;
        - предоставляет типобезопасный контейнер контекста для логирования.

    Границы:
        - не валидирует бизнес-правила значений;
        - не содержит поведение по отправке или хранению логов.

    Взаимодействие с другими ролями:
        - используется `TracingLogger` для детерминированного форматирования;
        - заполняется в сервисах и парсерах, где есть фактический контекст.
    """

    operation: str | None = None
    url: str | None = None
    page: int | None = None
    item_index: int | None = None
    parser_mode: str | None = None
