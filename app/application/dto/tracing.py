"""DTO и типы callback-событий для трассировки и UI-уведомлений.

Роль и ответственность:
    - задаёт типобезопасные структуры событий прогресса, статистики и ошибок элементов;
    - определяет единые сигнатуры callback-ов для use-case и UI-слоёв.

Границы:
    - не управляет выполнением сценариев парсинга;
    - не содержит UI-рендеринг и бизнес-логику обработки страниц.

Взаимодействие с другими ролями:
    - используется `ParseProductsUseCase` для публикации событий;
    - используется `StreamlitUI` как контракт входных данных callback-методов.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable


@dataclass(frozen=True, slots=True)
class ProgressEvent:
    """Событие изменения прогресса выполнения сценария парсинга.

    Роль и ответственность:
        - переносит текущий процент прогресса и статусное сообщение.

    Границы:
        - не интерпретирует прогресс и не выполняет форматирование UI.

    Взаимодействие с другими ролями:
        - создаётся use-case слоем;
        - потребляется callback-методом UI.
    """

    value: float
    status: str


@dataclass(frozen=True, slots=True)
class StatsEvent:
    """Событие публикации счётчиков обработки элементов.

    Роль и ответственность:
        - переносит общее количество элементов и число уже обработанных.

    Границы:
        - не рассчитывает производные показатели и не хранит агрегаты.

    Взаимодействие с другими ролями:
        - создаётся use-case слоем;
        - потребляется callback-методом UI.
    """

    total: int
    processed: int


@dataclass(frozen=True, slots=True)
class ItemErrorEvent:
    """Событие ошибки при обработке отдельного элемента.

    Роль и ответственность:
        - переносит индекс элемента и исходное исключение обработки.

    Границы:
        - не подавляет и не трансформирует исключения.

    Взаимодействие с другими ролями:
        - создаётся use-case слоем в блоке обработки ошибок;
        - потребляется callback-методом UI для уведомления пользователя.
    """

    index: int
    error: Exception


ProgressCallback = Callable[[ProgressEvent], None]
StatsCallback = Callable[[StatsEvent], None]
ErrorCallback = Callable[[ItemErrorEvent], None]
