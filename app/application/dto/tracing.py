"""DTO и типы callback-событий для трассировки и UI-уведомлений.

Роль и ответственность:
    - задаёт типизированные события прогресса, статистики и ошибок элементов;
    - определяет контракты callback-ов, используемых use-case и UI-слоем.

Границы:
    - не выполняет бизнес-операции парсинга и не рендерит интерфейс;
    - не управляет порядком вызовов callback-ов и политикой обработки ошибок.

Взаимодействие с другими ролями:
    - используется `ParseProductsUseCase` для публикации событий выполнения;
    - используется `StreamlitUI` для типобезопасного приема уведомлений.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass


@dataclass(slots=True, frozen=True)
class ProgressEvent:
    """Событие изменения прогресса выполнения сценария.

    Роль и ответственность:
        - переносит текущее значение прогресса и текстовый статус как единый DTO.

    Границы:
        - не инициирует операции и не хранит табличные результаты.

    Взаимодействие с другими ролями:
        - формируется use-case и потребляется UI-слоем для визуализации статуса.
    """

    progress: float
    status: str


@dataclass(slots=True, frozen=True)
class StatsEvent:
    """Событие обновления счётчиков обработки.

    Роль и ответственность:
        - переносит агрегированные значения «всего» и «обработано».

    Границы:
        - не определяет алгоритм подсчёта и не хранит сведения об ошибках.

    Взаимодействие с другими ролями:
        - формируется use-case и отображается UI-слоем в блоке статистики.
    """

    total: int
    processed: int


@dataclass(slots=True, frozen=True)
class ItemErrorEvent:
    """Событие ошибки обработки одного элемента.

    Роль и ответственность:
        - переносит индекс элемента и текст ошибки как типизированный DTO.

    Границы:
        - не хранит traceback и не управляет ретраями.

    Взаимодействие с другими ролями:
        - формируется use-case и передаётся UI для уведомления пользователя.
    """

    index: int
    error: str


ProgressCallback = Callable[[ProgressEvent], None]
StatsCallback = Callable[[StatsEvent], None]
ErrorCallback = Callable[[ItemErrorEvent], None]

